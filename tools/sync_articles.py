#!/usr/bin/env python3
"""Sync eligible owner articles into an editorial preview; never infer release approval.

    python3 tools/sync_articles.py --kb ../../msra-open-research

Source publication_state: ready means generation eligibility only. Source-checked
records default to editorial-draft, noindex and no sitemap entry. A published
record also needs explicit release_approved: true and a declared release_scope.
Locally adapted frontend_edited: true files stop the batch until reconciled.
"""
import argparse
from datetime import date
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit

from sync_research import front_matter, q

ROOT = Path(__file__).resolve().parent.parent
SAFE = re.compile(r'^[a-z0-9]+(?:-[a-z0-9]+)*$')
GENERATED = '<!-- Generated by tools/sync_articles.py.'
LABELS = {
    'guide': ('Owner guide', 'guide'),
    'explainer': ('Evidence explainer', 'explainer'),
    'study-analysis': ('Study analysis', 'analysis'),
    'research-update': ('Research update', 'update'),
}


def enabled(value):
    return value is True or str(value).lower() == 'true'


def iso_date(value, label, path):
    if not isinstance(value, str) or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', value):
        raise ValueError(f'{path}: use an ISO {label}')
    try:
        date.fromisoformat(value)
    except ValueError as error:
        raise ValueError(f'{path}: invalid {label}') from error


def validate(meta, path, topics):
    required = ['title', 'slug', 'topic', 'species', 'summary', 'date', 'content_type',
                'authors', 'publication_state', 'evidence_review_status', 'clinical_review_status']
    missing = [key for key in required if not meta.get(key)]
    if missing:
        raise ValueError(f'{path}: missing {", ".join(missing)}')
    if not SAFE.fullmatch(meta['slug']):
        raise ValueError(f'{path}: unsafe slug')
    if meta['topic'] not in topics:
        raise ValueError(f'{path}: unknown topic {meta["topic"]}')
    if meta['content_type'] not in LABELS:
        raise ValueError(f'{path}: unsupported article type')
    iso_date(meta['date'], 'article date', path)
    if meta.get('updated'):
        iso_date(meta['updated'], 'update date', path)
        if meta['updated'] < meta['date']:
            raise ValueError(f'{path}: update date precedes article date')
    if meta['publication_state'] == 'ready' and meta['evidence_review_status'] != 'source-checked':
        raise ValueError(f'{path}: eligible article has not cleared the source check')
    review = meta['clinical_review_status']
    if review not in ('not-independently-reviewed', 'independently-reviewed'):
        raise ValueError(f'{path}: unsupported clinical review status; preserve actual review information')
    if review == 'independently-reviewed':
        for key in ('clinical_reviewer', 'clinical_review_scope', 'clinical_review_date'):
            if not meta.get(key):
                raise ValueError(f'{path}: independent review requires {key}')
        iso_date(meta['clinical_review_date'], 'clinical review date', path)
    if enabled(meta.get('release_approved')):
        if meta['publication_state'] != 'ready' or meta['evidence_review_status'] != 'source-checked':
            raise ValueError(f'{path}: release approval requires ready, source-checked content')
        scope = meta.get('release_scope')
        if scope not in ('literature-interpretation', 'clinical-guidance'):
            raise ValueError(f'{path}: release approval requires a declared release_scope')
        if scope == 'clinical-guidance' and review != 'independently-reviewed':
            raise ValueError(f'{path}: clinical guidance requires recorded independent clinical review')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--kb', required=True, help='local open-research checkout')
    args = parser.parse_args(argv)
    kb = Path(args.kb).resolve()
    registry = json.loads((kb / 'content' / 'topics.json').read_text())
    topics = {topic['id']: topic for topic in registry['topics']}
    out = ROOT / '_articles'
    articles, skipped, slugs, prepared = [], [], set(), []
    source_docs = [(path, *front_matter(path.read_text())) for path in sorted((kb / 'content' / 'articles').glob('**/*.md')) if path.name != 'README.md']
    for path, meta, body in source_docs:
        validate(meta, path, topics)
    eligible = {path.resolve(): (topics[meta['topic']]['url'] + meta['slug'] + '/', enabled(meta.get('release_approved')))
                for path, meta, _ in source_docs if meta['publication_state'] == 'ready' and topics[meta['topic']]['status'] == 'active'}
    for path, meta, body in source_docs:
        if meta['publication_state'] != 'ready':
            skipped.append(str(path.relative_to(kb)))
            continue
        topic = topics[meta['topic']]
        if topic['status'] != 'active':
            raise ValueError(f'{path}: topic is not active')
        url = topic['url'] + meta['slug'] + '/'
        if url in slugs:
            raise ValueError(f'duplicate canonical article: {url}')
        slugs.add(url)
        if not re.search(r'https://(?:pubmed\.ncbi\.nlm\.nih\.gov|pmc\.ncbi\.nlm\.nih\.gov|doi\.org|www\.vet\.cornell\.edu)', body):
            raise ValueError(f'{path}: no primary/clinical source link found')
        label, card_label = LABELS[meta['content_type']]
        count = len(re.findall(r'\b\w+\b', body))
        released = enabled(meta.get('release_approved'))
        article = dict(meta, url=url, content_label=label, card_label=card_label,
                       reading_time=max(2, round(count / 210)), priority=int(meta.get('priority', 50)),
                       featured=enabled(meta.get('featured')), urgent=enabled(meta.get('urgent', 'true')),
                       source_publication_state=meta['publication_state'],
                       publication_state='published' if released else 'editorial-draft',
                       release_approved=released, robots='index,follow' if released else 'noindex',
                       sitemap=released)
        if isinstance(article['species'], str):
            article['species'] = [article['species']]
        headers = dict(article, layout='knowledge-article', editorial=True, permalink=url,
                       description=meta['summary'], last_modified_at=meta.get('updated', meta['date']),
                       excerpt_separator='')
        lines = ['---'] + [f'{key}: {q(value)}' for key, value in headers.items()] + ['---',
            '<!-- Generated by tools/sync_articles.py. Reconcile frontend_edited adaptations before regenerating from the open-research checkout. -->']
        body = re.sub(r'^\s*# [^\n]*\n+', '', body).strip()

        def rewrite_link(match):
            label, href = match.group(1), match.group(2)
            parsed = urlsplit(href)
            if parsed.scheme or href.startswith(('/', '#')) or not parsed.path.endswith('.md'):
                return match.group(0)
            target = (path.parent / unquote(parsed.path)).resolve()
            if target not in eligible:
                raise ValueError(f'{path}: source article link does not resolve to an eligible article: {href}')
            target_url, target_released = eligible[target]
            if released and not target_released:
                raise ValueError(f'{path}: released article links to an unapproved draft: {href}')
            suffix = ('?' + parsed.query if parsed.query else '') + ('#' + parsed.fragment if parsed.fragment else '')
            return f'{label}({target_url}{suffix})'

        body = re.sub(r'(\[[^\]]*\])\(([^)\s]+)\)', rewrite_link, body)
        prepared.append((out / f'{meta["topic"]}--{meta["slug"]}.md', '\n'.join(lines)+'\n'+body+'\n'))
        articles.append(article)
    # Inspect every overwrite and generated-file removal before mutating output.
    current = {dest.name for dest, _ in prepared}
    removals = []
    for old in out.glob('*.md'):
        old_text = old.read_text()
        old_meta, _ = front_matter(old_text)
        if old.name in current or GENERATED in old_text:
            if enabled(old_meta.get('frontend_edited')):
                raise ValueError(f'{old}: frontend_edited adaptation requires reconciliation; no files written')
        if old.name not in current and GENERATED in old_text:
            removals.append(old)
    out.mkdir(exist_ok=True)
    for dest, text in prepared:
        dest.write_text(text)
    for old in removals:
        old.unlink()
    articles.sort(key=lambda article: (article['priority'], article['title']))
    data = dict(registry, articles=articles, skipped_drafts=skipped)
    (ROOT / '_data' / 'knowledge.json').write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n')
    published = sum(article['release_approved'] for article in articles)
    print(f'{len(articles)} eligible articles synced ({published} explicitly released; {len(articles)-published} editorial previews); {len(skipped)} ineligible drafts withheld')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, FileNotFoundError) as error:
        sys.exit(str(error))
